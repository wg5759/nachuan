import { createHash } from 'node:crypto'
import { createReadStream, lstatSync, realpathSync } from 'node:fs'
import { dirname, join, parse, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

import { stageEnginePayload } from './engine-payload.mjs'
import { materializeGeneratedSourceModule } from './generated-source-module.mjs'
import { verifyPreparedMediaRuntime } from './media-runtime-policy.mjs'
import {
  ENGINE_PYTHON_PAYLOAD_MANIFEST,
  verifyPythonPayloadProvenance,
  writePythonPayloadProvenance
} from './python-payload-provenance.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..', '..')
const output = join(here, '..', 'src', 'main', 'generated-engine-integrity.ts')
const scriptPath = fileURLToPath(import.meta.url)

function assertBoundedRegular(path, maxBytes, label) {
  const info = lstatSync(path)
  if (!info.isFile() || info.isSymbolicLink() || info.size <= 0 || info.size > maxBytes) {
    throw new Error(`${label} must be a bounded regular file`)
  }
  const absolute = resolve(path)
  const root = parse(absolute).root
  let cursor = root
  for (const part of absolute.slice(root.length).split(sep).filter(Boolean)) {
    cursor = join(cursor, part)
    if (lstatSync(cursor).isSymbolicLink()) {
      throw new Error(`${label} path must not contain filesystem redirects`)
    }
  }
  realpathSync.native(path)
}

async function sha256(path) {
  const hash = createHash('sha256')
  await new Promise((accept, reject) => {
    const stream = createReadStream(path)
    stream.on('data', (chunk) => hash.update(chunk))
    stream.once('error', reject)
    stream.once('end', accept)
  })
  return hash.digest('hex')
}

export function renderEngineIntegrityModule({
  engineSha256,
  runtimeManifestSha256,
  ffmpegSha256,
  ffprobeSha256,
  mediaRuntimeManifestSha256,
  storeRuntimeProfileSha256
}) {
  return (
    `// Generated by scripts/write-engine-digest.mjs; do not hand-edit.\n` +
    `export const EXPECTED_PACKAGED_ENGINE_SHA256 = '${engineSha256}'\n` +
    `export const EXPECTED_LOCAL_RUNTIME_MANIFEST_SHA256 = '${runtimeManifestSha256}'\n` +
    `export const EXPECTED_PACKAGED_FFMPEG_SHA256 = '${ffmpegSha256}'\n` +
    `export const EXPECTED_PACKAGED_FFPROBE_SHA256 = '${ffprobeSha256}'\n` +
    `export const EXPECTED_MEDIA_RUNTIME_MANIFEST_SHA256 = '${mediaRuntimeManifestSha256}'\n` +
    `export const EXPECTED_STORE_RUNTIME_PROFILE_SHA256 = '${storeRuntimeProfileSha256}'\n`
  )
}

export async function prepareEngineIntegrityBindings({
  projectRoot = repoRoot,
  operation = 'write',
  clients = {}
} = {}) {
  if (operation !== 'write' && operation !== 'check') {
    throw new Error('engine integrity operation must be write or check')
  }
  const stagePayload = clients.stageEnginePayload || stageEnginePayload
  const writeProvenance = clients.writePythonPayloadProvenance || writePythonPayloadProvenance
  const verifyProvenance = clients.verifyPythonPayloadProvenance || verifyPythonPayloadProvenance
  const verifyMediaRuntime = clients.verifyPreparedMediaRuntime || verifyPreparedMediaRuntime
  for (const [name, client] of Object.entries({
    stageEnginePayload: stagePayload,
    writePythonPayloadProvenance: writeProvenance,
    verifyPythonPayloadProvenance: verifyProvenance,
    verifyPreparedMediaRuntime: verifyMediaRuntime
  })) {
    if (typeof client !== 'function') throw new Error(`engine integrity ${name} client is invalid`)
  }
  projectRoot = resolve(projectRoot)
  const engineName = process.platform === 'win32' ? 'engine.exe' : 'engine'
  const enginePath = join(projectRoot, 'dist', engineName)
  const stagedEnginePath = join(projectRoot, 'dist', 'engine.payload')
  const runtimeManifestPath = join(projectRoot, 'dist', 'local-runtime-manifest.json')
  const storeRuntimeProfilePath = join(
    projectRoot,
    'config',
    'store-runtime-profile.v1.json'
  )
  const provenancePath = join(projectRoot, 'dist', ENGINE_PYTHON_PAYLOAD_MANIFEST)
  assertBoundedRegular(enginePath, 1024 * 1024 * 1024, 'release engine')
  assertBoundedRegular(runtimeManifestPath, 256 * 1024, 'local runtime manifest')
  assertBoundedRegular(storeRuntimeProfilePath, 64 * 1024, 'store runtime profile')
  if (operation === 'write') {
    await stagePayload({ sourceEngine: enginePath, stagedEngine: stagedEnginePath })
    await writeProvenance({
      enginePath: stagedEnginePath,
      outputPath: provenancePath,
      projectRoot
    })
  } else {
    assertBoundedRegular(stagedEnginePath, 1024 * 1024 * 1024, 'staged release engine')
    assertBoundedRegular(provenancePath, 256 * 1024 * 1024, 'engine Python payload provenance')
    const sourceDigest = await sha256(enginePath)
    const stagedDigest = await sha256(stagedEnginePath)
    if (sourceDigest !== stagedDigest) {
      throw new Error('staged release engine differs from the signed release engine')
    }
    await verifyProvenance({
      enginePath: stagedEnginePath,
      manifestPath: provenancePath,
      projectRoot
    })
  }
  const engineSha256 = await sha256(stagedEnginePath)
  const runtimeManifestSha256 = await sha256(runtimeManifestPath)
  const storeRuntimeProfileSha256 = await sha256(storeRuntimeProfilePath)
  const mediaRuntime = await verifyMediaRuntime({ repoRoot: projectRoot })
  return {
    engineName,
    engineSha256,
    runtimeManifestSha256,
    ffmpegSha256: mediaRuntime.ffmpeg.sha256,
    ffprobeSha256: mediaRuntime.ffprobe.sha256,
    mediaRuntimeManifestSha256: mediaRuntime.manifestSha256,
    storeRuntimeProfileSha256
  }
}

export async function materializeEngineIntegrityModule({
  output: target = output,
  bindings,
  operation = 'write'
} = {}) {
  return await materializeGeneratedSourceModule({
    output: target,
    content: renderEngineIntegrityModule(bindings),
    operation
  })
}

async function main(operation = 'write') {
  const bindings = await prepareEngineIntegrityBindings({ operation })
  await materializeEngineIntegrityModule({ bindings, operation })
  console.log(
    `[engine-integrity] ${operation === 'check' ? 'verified' : 'staged'} post-signing ${bindings.engineName} as engine.payload sha256=${bindings.engineSha256}`
  )
  console.log(`[engine-integrity] bound local-runtime-manifest.json sha256=${bindings.runtimeManifestSha256}`)
  console.log(`[engine-integrity] bound unsigned fixed-hash media candidate manifest sha256=${bindings.mediaRuntimeManifestSha256}`)
  console.log(`[engine-integrity] bound store runtime profile sha256=${bindings.storeRuntimeProfileSha256}`)
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  try {
    await main(process.argv[2] || 'write')
  } catch (error) {
    console.error(`[engine-integrity] BLOCKED: ${error instanceof Error ? error.message : String(error)}`)
    process.exitCode = 1
  }
}
